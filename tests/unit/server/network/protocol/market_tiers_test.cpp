TEST(MarketTierOverviewTest, RejectsMalformedAndUnboundedRequests) {
	const std::string token = "0123456789abcdef0123456789abcdef";
	const auto packet = nlohmann::json { { "version", 1 }, { "action", "tiers" }, { "itemId", 58388 }, { "request", token } };
	const auto request = MarketTierOverview::parseRequest(packet.dump());
	ASSERT_TRUE(request);
	EXPECT_EQ(request->itemId, 58388);
	EXPECT_EQ(request->token, token);
	for (const auto &bad : { std::string("{"), std::string("[]"), std::string(257, 'x') }) {
		EXPECT_FALSE(MarketTierOverview::parseRequest(bad));
	}
	for (auto value : { nlohmann::json(-1), nlohmann::json(0), nlohmann::json(65536), nlohmann::json("58388"), nlohmann::json(58388.5) }) {
		auto bad = packet;
		bad["itemId"] = value;
		EXPECT_FALSE(MarketTierOverview::parseRequest(bad.dump()));
	}
	for (const auto &key : { "version", "action", "request" }) {
		auto bad = packet;
		bad[key] = nlohmann::json::array();
		EXPECT_FALSE(MarketTierOverview::parseRequest(bad.dump()));
	}
}

TEST(MarketTierOverviewTest, ReturnsAllTiersWithoutLosingPricePrecisionAndPreservesPacketBoundary) {
	const MarketTierOverview::Request request { 58388, "0123456789abcdef0123456789abcdef" };
	const std::vector<MarketTierOverview::Row> rows { { 0, 1, 3, 5, 45000000 }, { 2, 1, 1, 1, 98000000 }, { 2, 0, 2, 3, 87000000 }, { 4, 1, 1, 1, 999999999999 }, { 7, 0, 1, 2, 100000000 } };
	const auto response = MarketTierOverview::response(request, 10, rows);
	ASSERT_TRUE(response["ok"].get<bool>());
	ASSERT_EQ(response["tiers"].size(), 11U);
	EXPECT_EQ(response["tiers"][0]["bestSell"], "45000000");
	EXPECT_EQ(response["tiers"][2]["buyOffers"], 2);
	EXPECT_EQ(response["tiers"][2]["bestBuy"], "87000000");
	EXPECT_EQ(response["tiers"][4]["bestSell"], "999999999999");
	EXPECT_EQ(response["tiers"][3]["sellOffers"], 0);
	EXPECT_EQ(response["tiers"][3]["bestSell"], "0");
	EXPECT_EQ(response["tiers"][7]["buyAmount"], "2");
	RecordProperty("tier_payload", response.dump());
	RecordProperty("tier_query", MarketTierOverview::query(58388, 10, 1000));
	NetworkMessage msg;
	MarketTierOverview::writePacket(msg, response);
	msg.addByte(0x1D);
	msg.setBufferPosition(NetworkMessage::INITIAL_BUFFER_POSITION);
	EXPECT_EQ(msg.getByte(), 0x32);
	EXPECT_EQ(msg.getByte(), 91);
	EXPECT_EQ(nlohmann::json::parse(msg.getString()), response);
	EXPECT_EQ(msg.getByte(), 0x1D);
	EXPECT_FALSE(msg.isOverrun());
}

TEST(MarketTierOverviewTest, EmptyBookDiffersFromQueryFailureAndTierLimitIsRespected) {
	const MarketTierOverview::Request request { 58388, "0123456789abcdef0123456789abcdef" };
	const auto empty = MarketTierOverview::response(request, 2, std::vector<MarketTierOverview::Row> {});
	EXPECT_TRUE(empty["ok"].get<bool>());
	ASSERT_EQ(empty["tiers"].size(), 3U);
	for (const auto &tier : empty["tiers"]) {
		EXPECT_EQ(tier["buyOffers"], 0);
	}
	const auto failure = MarketTierOverview::response(request, 10, std::nullopt);
	EXPECT_FALSE(failure["ok"].get<bool>());
	EXPECT_FALSE(failure.contains("tiers"));
	EXPECT_EQ(MarketTierOverview::response(request, 255, std::vector<MarketTierOverview::Row> {})["tiers"].size(), 11U);
}

// Enabled only by the isolated PostgreSQL harness, never by the configured
// gameplay database. Each test rolls back all fixture tables and rows.
class MarketNamedOffersTest : public ::testing::Test {
protected:
	void SetUp() override {
		const auto socket = std::getenv("CANARY_MARKET_TEST_SOCKET");
		if (!socket) {
			GTEST_SKIP() << "Run via OTClient tests/market_tier_query_test.py --named-offers";
		}
		const std::string path = socket;
		ASSERT_TRUE(path.starts_with("/tmp/market-tier-db-") || path.starts_with("/private/tmp/market-tier-db-"));
		previous = DI::getTestContainer();
		InMemoryLogger::install(injector);
		DI::setTestContainer(&injector);
		installed = true;
		g_configManager().setConfigFileLua("config.lua.dist");
		ASSERT_TRUE(g_configManager().load());
		const std::string host = "localhost", user = "market_tier_test", password, database = "market_named_test";
		ASSERT_TRUE(g_database().connect(&host, &user, &password, &database, 55449, &path));
		ASSERT_TRUE(g_database().executeQuery("BEGIN"));
		ASSERT_TRUE(g_database().executeQuery("CREATE TABLE players(id integer PRIMARY KEY, name text NOT NULL)"));
		ASSERT_TRUE(g_database().executeQuery("CREATE TABLE market_offers(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, player_id integer, sale smallint, itemtype bigint, amount integer, created numeric(20), anonymous smallint DEFAULT 0, price numeric(20), tier smallint)"));
		ASSERT_TRUE(g_database().executeQuery("INSERT INTO players VALUES (17, 'Named buyer'), (18, 'Named seller')"));
	}
	void TearDown() override {
		if (!installed) {
			return;
		}
		g_database().executeQuery("ROLLBACK");
		DI::setTestContainer(previous);
	}
	di::extension::injector<> injector;
	decltype(DI::getTestContainer()) previous = nullptr;
	bool installed = false;
};

TEST_F(MarketNamedOffersTest, ExistingAnonymousOrdersShowOwnersAcrossEveryReadPath) {
	ASSERT_TRUE(g_database().executeQuery("INSERT INTO market_offers(id, player_id, sale, itemtype, amount, created, anonymous, price, tier) VALUES (1,17,0,58388,2,1000,1,45000000,0),(2,18,1,58388,1,1000,1,98000000,2)"));
	const auto allBuy = IOMarket::getActiveOffers(MARKETACTION_BUY);
	const auto allSell = IOMarket::getActiveOffers(MARKETACTION_SELL);
	const auto tierBuy = IOMarket::getActiveOffers(MARKETACTION_BUY, 58388, 0);
	const auto tierSell = IOMarket::getActiveOffers(MARKETACTION_SELL, 58388, 2);
	ASSERT_EQ(allBuy.size(), 1U);
	ASSERT_EQ(allSell.size(), 1U);
	ASSERT_EQ(tierBuy.size(), 1U);
	ASSERT_EQ(tierSell.size(), 1U);
	EXPECT_EQ(allBuy.front().playerName, "Named buyer");
	EXPECT_EQ(allSell.front().playerName, "Named seller");
	EXPECT_EQ(tierBuy.front().playerName, "Named buyer");
	EXPECT_EQ(tierSell.front().playerName, "Named seller");
	EXPECT_EQ(IOMarket::getOfferByCounter(tierBuy.front().timestamp, tierBuy.front().counter).playerName, "Named buyer");
	EXPECT_EQ(IOMarket::getOfferByCounter(tierSell.front().timestamp, tierSell.front().counter).playerName, "Named seller");
	EXPECT_EQ(tierBuy.front().amount, 2);
	EXPECT_EQ(tierSell.front().amount, 1);
	const auto untouched = g_database().storeQuery("SELECT COUNT(*) AS count FROM market_offers WHERE anonymous = 1");
	ASSERT_TRUE(untouched);
	EXPECT_EQ(untouched->getNumber<uint32_t>("count"), 2U);
}

TEST_F(MarketNamedOffersTest, LegacyAnonymousCreationFlagCannotCreateHiddenBuyOrSellOrders) {
	IOMarket::createOffer(17, MARKETACTION_BUY, 58388, 3, 45000000, 0, true);
	IOMarket::createOffer(18, MARKETACTION_SELL, 58388, 1, 98000000, 2, true);
	const auto result = g_database().storeQuery("SELECT anonymous, sale, amount, tier FROM market_offers ORDER BY id");
	ASSERT_TRUE(result);
	EXPECT_EQ(result->getNumber<uint16_t>("anonymous"), 0);
	EXPECT_EQ(result->getNumber<uint16_t>("sale"), MARKETACTION_BUY);
	EXPECT_EQ(result->getNumber<uint16_t>("amount"), 3);
	EXPECT_EQ(result->getNumber<uint16_t>("tier"), 0);
	ASSERT_TRUE(result->next());
	EXPECT_EQ(result->getNumber<uint16_t>("anonymous"), 0);
	EXPECT_EQ(result->getNumber<uint16_t>("sale"), MARKETACTION_SELL);
	EXPECT_EQ(result->getNumber<uint16_t>("tier"), 2);
	EXPECT_EQ(IOMarket::getActiveOffers(MARKETACTION_BUY).front().playerName, "Named buyer");
	EXPECT_EQ(IOMarket::getActiveOffers(MARKETACTION_SELL).front().playerName, "Named seller");
}
